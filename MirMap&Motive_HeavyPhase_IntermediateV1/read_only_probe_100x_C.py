for agent in prompt_agents:
    path = os.path.join(AGENTS_DIR, agent)
    if os.path.exists(path):
        with open(path, 'r', encoding='utf-8-sig') as f:
            lines = f.readlines()
            for i, line in enumerate(lines):
                # Search for hardcoded strings that make up the prompt
                if ('prompt' in line.lower() or 'instruction' in line.lower()) and ('=' in line or ':' in line):
                    # Only print if it looks like a string assignment
                    if '"' in line or "'" in line:
                        clean_code = line.strip()[:150]
                        print(f'  [*] Found Prompt Generator in {agent} at Line {i+1}:')
                        print(f'      -> Code: {clean_code}')

